# Generator for authentic NES Zelda Intro (src/intro.asm)
import sys

with open('zelda.nes', 'rb') as f:
    rom = f.read()

b6 = rom[16 + 6*0x4000 : 16 + 7*0x4000]
idx = 0xA869 - 0x8000
nt = [0x24] * 1024

while idx < len(b6):
    vram_hi = b6[idx]
    if vram_hi == 0xFF: break
    vram_lo = b6[idx+1]
    count_byte = b6[idx+2]
    idx += 3
    is_rle = (count_byte & 0x40) != 0
    count = count_byte & 0x3F
    addr = ((vram_hi << 8) | vram_lo) - 0x2000
    if is_rle:
        val = b6[idx]
        idx += 1
        for i in range(count):
            if 0 <= addr + i < 1024: nt[addr + i] = val
    else:
        for i in range(count):
            if 0 <= addr + i < 1024: nt[addr + i] = b6[idx + i]
        idx += count

shield_tiles = []
for r in range(5, 17):
    for c in range(5, 27):
        t = nt[r*32 + c]
        if t != 0x24:
            shield_tiles.append(t)

uniq_shield = sorted(set(shield_tiles))
nes_to_c64 = {t: 140 + i for i, t in enumerate(uniq_shield)}

shield_chars = []
shield_colors = []
for r in range(5, 17):
    for c in range(5, 27):
        t = nt[r*32 + c]
        if t == 0x24:
            shield_chars.append(32)
            shield_colors.append(0)
        else:
            shield_chars.append(nes_to_c64[t])
            if t in (0xE2, 0xE3, 0xE4, 0xE5, 0xE6):
                shield_colors.append(5) # COL_GREEN (vines and leaves)
            elif 0x70 <= t <= 0x7B:
                shield_colors.append(1) # COL_WHITE (ribbon "THE LEGEND OF")
            elif t in (0x81, 0x82, 0x83, 0x90, 0x91, 0x92, 0x93, 0xA1, 0xA2, 0xA3, 0xA4, 0xB2, 0xB3, 0xB4, 0xB5):
                shield_colors.append(7) # COL_YELLOW (golden Triforce)
            elif t in (0xC6, 0xC7, 0xC8, 0xE8, 0xE9, 0xD3):
                shield_colors.append(1) # COL_WHITE (sword blade)
            elif t in (0xEA, 0xEB, 0xEC):
                shield_colors.append(3) # COL_CYAN (ribbon wrapped on sword)
            elif t in (0xCE, 0xCF, 0xD1, 0xD2):
                shield_colors.append(7) # COL_YELLOW (sword hilt)
            else:
                shield_colors.append(2) # COL_RED (ZELDA letters with 3D drop shadow)

# Link holding Triforce sprite (multicolor, 64 bytes)
sprite_rows = [
    "....YYYY....", # Row 0: Triforce tip
    "...YYYYYY...", # Row 1
    "..YYYYYYYY..", # Row 2
    ".YYYYYYYYYY.", # Row 3
    "YYYYYYYYYYYY", # Row 4: Triforce base
    "....FFFF....", # Row 5: Raised hands holding it
    "...FFFFFF...", # Row 6: Wrists / Forearms
    "...GGGGGG...", # Row 7: Link's green cap
    "..GGGGGGGG..", # Row 8
    "..FFFFFFFF..", # Row 9: Face / Eyes
    "...FFFFFF...", # Row 10: Chin
    "..GGGGGGGG..", # Row 11: Shoulders
    ".GGGGGGGGGG.", # Row 12: Chest / Tunic
    ".GGGGGGGGGG.", # Row 13
    "..FFFFFFFF..", # Row 14: Belt / Buckle
    ".GGGGGGGGGG.", # Row 15: Tunic bottom
    "..GG....GG..", # Row 16: Legs
    "..FF....FF..", # Row 17: Boots
    "..FF....FF..", # Row 18
    ".FFFF..FFFF.", # Row 19: Feet
    "............", # Row 20
]

bit_map = {'.': 0b00, 'G': 0b01, 'F': 0b11, 'Y': 0b10}
spr_link_bytes = []
for row in sprite_rows:
    b0 = (bit_map[row[0]] << 6) | (bit_map[row[1]] << 4) | (bit_map[row[2]] << 2) | bit_map[row[3]]
    b1 = (bit_map[row[4]] << 6) | (bit_map[row[5]] << 4) | (bit_map[row[6]] << 2) | bit_map[row[7]]
    b2 = (bit_map[row[8]] << 6) | (bit_map[row[9]] << 4) | (bit_map[row[10]] << 2) | bit_map[row[11]]
    spr_link_bytes.extend([b0, b1, b2])
spr_link_bytes.append(0)

