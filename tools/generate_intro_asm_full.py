spr_wave_bytes = []
for row in wave_spr_rows:
    # 24 chars -> 3 bytes
    b0 = sum(1 << (7 - i) for i in range(8) if row[i] == '#')
    b1 = sum(1 << (7 - i) for i in range(8) if row[8 + i] == '#')
    b2 = sum(1 << (7 - i) for i in range(8) if row[16 + i] == '#')
    spr_wave_bytes.extend([b0, b1, b2])
spr_wave_bytes.append(0)

